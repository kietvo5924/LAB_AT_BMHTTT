    private void btn_encryptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_encryptActionPerformed
        String algo = (String) cbo_algo.getSelectedItem();
        String plain = txt_plaintext.getText();
        String key = txt_key.getText();
        if (plain.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Hãy nhập Plaintext.");
            return;
        }
        try {
            String cipher = CipherTongHop.encrypt(algo, plain, key);
            txt_ciphertext.setText(cipher);
            String dbStatus = HistoryDao.tryInsert(algo, "ENCRYPT", plain, cipher);
            lbl_status.setText("Đã mã hóa (" + algo + "). " + dbStatus);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }// TODO add your handling code here:
    }//GEN-LAST:event_btn_encryptActionPerformed

    private void btn_decryptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_decryptActionPerformed
        String algo = (String) cbo_algo.getSelectedItem();
        String cipher = txt_ciphertext.getText();
        String key = txt_key.getText();
        if (cipher.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Hãy nhập Ciphertext.");
            return;
        }
        try {
            String plain = CipherTongHop.decrypt(algo, cipher, key);
            txt_plaintext.setText(plain);
            String dbStatus = HistoryDao.tryInsert(algo, "DECRYPT", cipher, plain);
            lbl_status.setText("Đã giải mã (" + algo + "). " + dbStatus);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }// TODO add your handling code here:
    }//GEN-LAST:event_btn_decryptActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
        String algo = (String) cbo_algo.getSelectedItem();
        String fileName = (algo != null ? algo.toLowerCase().replace(" ", "_") : "cipher") + "_output.txt";
        String path = FileTextIO.saveText(this, txt_ciphertext, fileName);
        if (path != null) {
            lbl_status.setText("Đã lưu tệp: " + path);
        }// TODO add your handling code here:
    }//GEN-LAST:event_btn_saveActionPerformed

