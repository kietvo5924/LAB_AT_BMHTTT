    private void btn_testActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_testActionPerformed
        try {
            int port = Integer.parseInt(txt_port.getText().trim());
            String server = txt_server.getText().trim();
            String db = txt_database.getText().trim();
            String user = txt_user.getText().trim();
            String pwd = txt_password.getText().trim(); // Lấy mật khẩu và loại bỏ khoảng trắng thừa
            
            DbConfig.set(server, port, db, user, pwd.toCharArray());
            lbl_status.setText("<html>" + DbConfig.test() + "</html>");
            JOptionPane.showMessageDialog(this, "Kết nối CSDL thành công!");
        } catch (Exception ex) {
            DbConfig.clear();
            lbl_status.setText("<html>Kết nối thất bại: " + ex.getMessage() + "</html>");
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Không kết nối được SQL Server", JOptionPane.ERROR_MESSAGE);
        }// TODO add your handling code here:
    }//GEN-LAST:event_btn_testActionPerformed

